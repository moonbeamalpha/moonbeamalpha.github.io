def banner_edits(total_label: str, exam_count: int):
    """Anchored aggregate edits for linkedin-banner.html. Keyed off the stat-label
    text so only the two headline numbers (Questions, Exams) are ever touched."""
    return [
        (r'(stat-number stat-number--cyan">)[\d,]+\+?'
         r'(</div>\s*<div class="stat-label">Practice Questions)',
         r'\g<1>' + total_label + r'\g<2>'),
        (r'(stat-number stat-number--purple">)\d+'
         r'(</div>\s*<div class="stat-label">Exams)',
         r'\g<1>' + str(exam_count) + r'\g<2>'),
    ]


def og_edits(total_label: str, exam_count: int, cert_paths: int):
    """Anchored aggregate edits for og-image.html's stats bar (Exams • Questions •
    Cert Paths). Each number is keyed off its trailing label span."""
    return [
        (r'(stat-num stat-num--cyan">)\d+(</span>Exams)',
         r'\g<1>' + str(exam_count) + r'\g<2>'),
        (r'(stat-num stat-num--gold">)[\d,]+\+?(</span>Questions)',
         r'\g<1>' + total_label + r'\g<2>'),
        (r'(stat-num stat-num--green">)\d+(</span>Cert Paths)',
         r'\g<1>' + str(cert_paths) + r'\g<2>'),
    ]


def warn_pill_drift(path: str, counts: dict, exam_count: int) -> None:
    """Print a warning if the exam pills shown on an image drift from the catalogue.
    Pills are hand-coloured/grouped, so this only reports — it never rewrites them."""
    if not os.path.exists(path):
        return
    shown = set(PILL_RE.findall(open(path).read()))
    rel = os.path.relpath(path, ROOT)
    missing = sorted(set(counts) - shown)   # in catalogue, absent from image
    extra = sorted(shown - set(counts))     # on image, absent from catalogue
    if not missing and not extra and len(shown) == exam_count:
        print(f"  pills ok  {rel}: all {exam_count} exams shown")
        return
    print(f"  PILLS     {rel}: shows {len(shown)}, catalogue has {exam_count}")
    if missing:
        print(f"            add by hand:    {', '.join(missing)}")
    if extra:
        print(f"            remove by hand: {', '.join(extra)}")


def find_chrome() -> str | None:
    """Locate a Chrome/Chromium binary (env CHROME wins)."""
    env = os.environ.get("CHROME")
    if env and os.path.exists(env):
        return env
    mac = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
    if os.path.exists(mac):
        return mac
    chromium = "/Applications/Chromium.app/Contents/MacOS/Chromium"
    if os.path.exists(chromium):
        return chromium
    for name in ("google-chrome", "google-chrome-stable", "chromium",
                 "chromium-browser", "chrome"):
        found = shutil.which(name)
        if found:
            return found
    return None


def html_dimensions(path: str) -> tuple[int, int] | None:
    """Pull the CSS pixel size out of the `html, body { width:Npx; height:Mpx }`
    rule so the screenshot matches whatever the HTML declares."""
    m = re.search(r'html,\s*body\s*\{[^}]*?width:\s*(\d+)px[^}]*?height:\s*(\d+)px',
                  open(path).read())
    return (int(m.group(1)), int(m.group(2))) if m else None


def render_png(chrome: str, port: int, html_path: str, png_path: str) -> bool:
    """Screenshot html_path -> png_path via headless Chrome at 2x device scale.
    Served over HTTP (not file://) so the banner's root-absolute /images/ paths
    and the Google Fonts both resolve. Writes atomically; keeps the old PNG on
    failure."""
    dims = html_dimensions(html_path)
    if not dims:
        print(f"  render SKIP {os.path.relpath(png_path, ROOT)}: no html/body size")
        return False
    w, h = dims
    url = f"http://127.0.0.1:{port}/{os.path.relpath(html_path, ROOT)}"
    tmp = png_path + ".tmp.png"
    cmd = [chrome, "--headless=new", "--disable-gpu", "--hide-scrollbars",
           "--force-device-scale-factor=2", f"--window-size={w},{h}",
           "--default-background-color=00000000", "--virtual-time-budget=10000",
           f"--screenshot={tmp}", url]
    try:
        subprocess.run(cmd, check=True, timeout=120,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except (subprocess.CalledProcessError, subprocess.TimeoutExpired) as exc:
        if os.path.exists(tmp):
            os.remove(tmp)
        print(f"  render FAIL {os.path.relpath(png_path, ROOT)}: {exc}")
        return False
    os.replace(tmp, png_path)
    print(f"  rendered    {os.path.relpath(png_path, ROOT)} ({w * 2}x{h * 2})")
    return True


def optimise_png(path: str) -> None:
    """Quantise a freshly-rendered social PNG to a 256-colour palette in place.
    Chrome's screenshots are full 24-bit RGB/RGBA PNGs; these are mostly a flat
    gradient plus a few embedded phone screenshots, so a 256-colour palette
    loses nothing visible while cutting the file to a third of its size or
    better. No new dependency: Pillow is already a soft requirement of the
    render path, guarded here exactly like it is everywhere else -- if it is
    missing, warn and leave the (larger) true-colour PNG in place rather than
    fail the run."""
    try:
        from PIL import Image
    except ImportError:
        print(f"  warning: Pillow not installed, cannot optimise "
              f"{os.path.relpath(path, ROOT)} (pip install pillow)")
        return
    before = os.path.getsize(path)
    im = Image.open(path)
    if im.mode in ("RGBA", "LA") or (im.mode == "P" and "transparency" in im.info):
        # MEDIANCUT/MAXCOVERAGE cannot quantize RGBA; FASTOCTREE is the only
        # alpha-safe method Pillow ships without libimagequant (not installed
        # on this machine -- see Tooling facts).
        quantized = im.convert("RGBA").quantize(colors=256, method=Image.Quantize.FASTOCTREE)
    else:
        quantized = im.convert("RGB").quantize(
            colors=256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.FLOYDSTEINBERG)
    quantized.save(path, optimize=True)
    after = os.path.getsize(path)
    print(f"  optimised   {os.path.relpath(path, ROOT)}: {before:,} -> {after:,} bytes "
          f"({100 * (1 - after / before):.0f}% smaller)")


def convert_to_jpeg(png_path: str, jpg_path: str) -> None:
    """Convert a rendered per-exam OG card from PNG to JPEG and remove the PNG.
    Per-exam cards are JPEG, not PNG, unlike the two shared images: a card is
    almost entirely flat gradient plus text with no embedded photos, so it
    compresses far smaller as quality-82 JPEG than as a 256-colour PNG palette
    -- comfortably inside the ~150 KB per-card target. Same Pillow guard as
    optimise_png(); if Pillow is missing, the PNG is left behind unconverted
    rather than the run failing."""
    try:
        from PIL import Image
    except ImportError:
        print(f"  warning: Pillow not installed, cannot convert "
              f"{os.path.relpath(png_path, ROOT)} to JPEG")
        return
    im = Image.open(png_path).convert("RGB")
    im.save(jpg_path, "JPEG", quality=82, optimize=True, progressive=True)
    size = os.path.getsize(jpg_path)
    os.remove(png_path)
    print(f"  rendered    {os.path.relpath(jpg_path, ROOT)} ({size:,} bytes)")


def render_exam_cards(chrome: str, port: int, data: dict, retired: set) -> None:
    """Render every exam's OG card: fill apps/AzureMastery/og-exam.html's
    {{CODE}}/{{NAME}}/{{COUNT}} placeholders and its accent custom properties,
    screenshot it via the same render_png() the two shared images use, then
    convert to JPEG. The count always comes from data["exams"][code] -- never
    hand-write it -- and the exam name from the names snapshot refresh_from_app()
    wrote into data/exam-counts.json, so this loop needs no app-repo checkout."""
    if not os.path.exists(OG_EXAM_HTML):
        print("  render SKIP: apps/AzureMastery/og-exam.html missing")
        return
    names = data.get("names") or {}
    counts = {k.upper(): v for k, v in data["exams"].items()}
    template = open(OG_EXAM_HTML).read()
    os.makedirs(OG_DIR, exist_ok=True)
    try:
        for code in sorted(counts):
            count = counts[code]
            name = names.get(code, code)
            accent, accent2 = exam_accent(code)
            page_html = (
                template
                .replace("{{CODE}}", html.escape(code, quote=False))
                .replace("{{NAME}}", html.escape(name, quote=False))
                .replace("{{COUNT}}", str(count))
                .replace("{{ACCENT}}", accent)
                .replace("{{ACCENT2}}", accent2)
            )
            if code in retired:
                page_html, k = PILL_COUNT_RE.subn(PILL_RETIRED, page_html)
                if not k:
                    print(f"  warning: {code} retired-pill swap matched 0 times "
                          f"-- og-exam.html's pill markup may have drifted")
            with open(OG_EXAM_TMP, "w") as fh:
                fh.write(page_html)
            dir_ = code_to_dir(code)
            png_path = os.path.join(OG_DIR, f"{dir_}.png")
            jpg_path = os.path.join(OG_DIR, f"{dir_}.jpg")
            if render_png(chrome, port, OG_EXAM_TMP, png_path):
                convert_to_jpeg(png_path, jpg_path)
    finally:
        if os.path.exists(OG_EXAM_TMP):
            os.remove(OG_EXAM_TMP)


def _serve_root() -> tuple[http.server.ThreadingHTTPServer, int]:
    """Serve ROOT on an ephemeral localhost port in a daemon thread."""
    class Quiet(http.server.SimpleHTTPRequestHandler):
        def log_message(self, *args):  # silence per-request logging
            pass
    handler = functools.partial(Quiet, directory=ROOT)
    httpd = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    return httpd, httpd.server_address[1]


def sync_social_images(p: "Patcher", counts: dict, total_label: str,
                       exam_count: int, cert_paths: int, render: bool,
                       data: dict, retired: set) -> None:
    print("social images:")
    p.apply(BANNER_HTML, banner_edits(total_label, exam_count))
    p.apply(OG_HTML, og_edits(total_label, exam_count, cert_paths))
    warn_pill_drift(BANNER_HTML, counts, exam_count)
    warn_pill_drift(OG_HTML, counts, exam_count)

    if p.check_only or not render:
        return
    chrome = find_chrome()
    if not chrome:
        print("  render SKIP: no Chrome/Chromium found "
              "(install Google Chrome or set env CHROME); PNGs left unchanged")
        return
    httpd, port = _serve_root()
    try:
        if render_png(chrome, port, BANNER_HTML, BANNER_PNG):
            optimise_png(BANNER_PNG)
        if render_png(chrome, port, OG_HTML, OG_PNG):
            optimise_png(OG_PNG)
        print("exam OG cards:")
        render_exam_cards(chrome, port, data, retired)
    finally:
        httpd.shutdown()


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--refresh", action="store_true",
                    help="re-read counts from the app repo into data/exam-counts.json")
    ap.add_argument("--check", action="store_true",
                    help="report files that would change; write nothing")
    ap.add_argument("--social-only", action="store_true",
                    help="only sync the social images (banner + og-image)")
    ap.add_argument("--no-render", action="store_true",
                    help="patch HTML/counts but skip rendering the social PNGs")
    ap.add_argument("--app-repo", default=DEFAULT_APP_REPO,
                    help=f"path to the AZ-104 Mastery checkout (default: {DEFAULT_APP_REPO})")
    args = ap.parse_args()

    data = refresh_from_app(args.app_repo) if args.refresh else load_data()

    # counts = the advertised per-exam number for every page, including the
    # non-current ones. active = the subset that feeds headline aggregates.
    counts = {k.upper(): v for k, v in data["exams"].items()}
    retired = non_current_exams(data)
    active = {code: n for code, n in counts.items() if code not in retired}
    # catalogue_count = every exam page that exists (sit-able + retired
    # reference pages) — the basis for the homepage ItemList's numberOfItems,
    # which is deliberately not exam_count.
    catalogue_count = len(counts)

    # Aggregates are read verbatim from the app's generated catalog-totals.json
    # rather than summed here — that file is what the App Store listing quotes,
    # and recomputing would let the two drift apart again.
    totals = data.get("totals") or {}
    if not totals:
        sys.exit("error: data/exam-counts.json predates catalog-totals.json — "
                 "re-run with --refresh against the app repo.")
    total = totals["questionCount"]
    exam_count = totals["examCount"]
    total_label = totals["questionCountLabel"]      # prose, e.g. "10,300+"
    metric_total = str((total // 100) * 100)        # comma-less for the count-up
    cert_paths = data.get("cert_path_count") or 0

    if exam_count != len(active):
        print(f"  warning: totals say {exam_count} current exams, catalogue lists "
              f"{len(active)} — re-run with --refresh.")

    print(f"counts: {exam_count} current exams, {total} exam-scoped questions "
          f"-> label {total_label} (metric {metric_total}), {cert_paths} current cert paths")
    if retired:
        print(f"        non-current, excluded from aggregates: {', '.join(sorted(retired))}")

    p = Patcher(check_only=args.check)

    if not args.social_only:
        print("exam pages:")
        for code, n in sorted(counts.items()):
            page = os.path.join(EXAMS_DIR, code_to_dir(code), "index.html")
            if not os.path.exists(page):
                print(f"  skip (missing): exams/{code_to_dir(code)}/index.html")
                continue
            # own-exam anchored edits
            original = open(page).read()
            text = original
            for pat, rep in exam_page_edits(code, n):
                text = re.sub(pat, rep, text)
            # cross-referenced related cards (any exam -> its count)
            text, _ = patch_related_cards(text, counts)
            rel = os.path.relpath(page, ROOT)
            if text != original:
                p.changed_files += 1
                if args.check:
                    print(f"  DRIFT  {rel}")
                else:
                    open(page, "w").write(text)
                    print(f"  synced {rel}")

        print("homepage:")
        p.apply(INDEX_HTML,
                homepage_edits(total_label, metric_total, exam_count, cert_paths,
                               len(retired), catalogue_count),
                transforms=[lambda t: patch_exam_code_lists(t, retired),
                            lambda t: patch_more_certifications(t, exam_count, retired),
                            lambda t: patch_roadmap_category_counts(t, retired)])

        print("llms.txt:")
        p.apply(LLMS_TXT, llms_edits(counts, total_label, exam_count),
                transforms=[lambda t: patch_llms_section_counts(t, retired)])

        warn_retired_markup(p, retired, set(counts))
        warn_itemlist_count(catalogue_count)

    sync_social_images(p, active, total_label, exam_count, cert_paths,
                       render=not args.no_render, data=data, retired=retired)

    verb = "would change" if args.check else "changed"
    print(f"\n{p.changed_files} file(s) {verb}.")
    if p.problems:
        print(f"{p.problems} markup problem(s) need a hand fix — see RETIRED lines above.")
    if args.check and (p.changed_files or p.problems):
        sys.exit(1)


if __name__ == "__main__":
    main()
