def refresh_from_app(app_repo: str) -> dict:
    catalog = os.path.join(app_repo, "App", "AzureMastery", "Resources", "exam-catalog.json")
    if not os.path.exists(catalog):
        sys.exit(f"error: app catalogue not found at {catalog}\n"
                 f"set AZURE_MASTERY_APP_REPO to the AZ-104 Mastery checkout.")
    with open(catalog) as fh:
        entries = json.load(fh)["exams"]

    # examQuestionCount is the blueprint-classified, exam-scoped count the app
    # advertises. It is 0 for a non-current exam; those pages fall back to the
    # full bank size so a retired page still states what it actually contains.
    # `name` is snapshotted too (Task A8) so the per-exam OG card render loop
    # and CI never need their own app-repo checkout to know an exam's title.
    exams, banks, retirement, retired, names = {}, {}, {}, [], {}
    for entry in entries:
        code = entry["code"]
        scoped = entry.get("examQuestionCount") or 0
        banks[code] = entry["questionCount"]
        exams[code] = scoped or entry["questionCount"]
        names[code] = entry["name"]
        if not scoped:
            retired.append(code)
        date = (entry.get("lifecycle") or {}).get("retirementDate")
        if date:
            retirement[code] = date

    totals_path = os.path.join(app_repo, "App", "AppStoreAssets", "catalog-totals.json")
    if not os.path.exists(totals_path):
        sys.exit(f"error: generated totals not found at {totals_path}\n"
                 f"run Tools/generate-exam-catalog.py in the app repo first.")
    with open(totals_path) as fh:
        totals = json.load(fh)
    if totals["examCount"] != len(exams) - len(retired):
        print(f"  warning: catalog-totals.json counts {totals['examCount']} current exams "
              f"but the catalogue has {len(exams) - len(retired)} with exam-scoped questions.")

    registry = os.path.join(app_repo, "App", "AzureMastery", "Data", "CertPathRegistry.swift")
    cert_paths = None
    if os.path.exists(registry):
        # A path is legacy when it declares replacedByPathID (CertPathDefinition
        # .isLegacy), so subtract those to land on CertPathRegistry.currentPaths.
        swift = open(registry).read()
        defined = swift.count("CertPathDefinition(")
        legacy = swift.count("replacedByPathID:")
        if not 0 < legacy < defined:
            print(f"  warning: read {legacy} legacy of {defined} cert paths, which looks wrong — "
                  f"check CertPathRegistry.swift still spells `replacedByPathID:` inline.")
        cert_paths = defined - legacy

    data = {"exams": exams, "bank_totals": banks, "retired": sorted(retired),
            "retirement_dates": retirement, "totals": totals,
            "cert_path_count": cert_paths, "names": names}
    os.makedirs(os.path.dirname(DATA_FILE), exist_ok=True)
    with open(DATA_FILE, "w") as fh:
        json.dump(data, fh, indent=2, sort_keys=True)
        fh.write("\n")
    print(f"refreshed {DATA_FILE}: {len(exams)} banks, {len(retired)} non-current; "
          f"advertising {totals['examCount']} exams / {totals['questionCountLabel']} "
          f"({totals['questionCount']} exam-scoped of {sum(banks.values())} authored), "
          f"{cert_paths} current cert paths")
    return data


def load_data() -> dict:
    if not os.path.exists(DATA_FILE):
        sys.exit(f"error: {DATA_FILE} missing — run with --refresh first.")
    with open(DATA_FILE) as fh:
        return json.load(fh)


def non_current_exams(data: dict) -> set:
    """Exam codes the app classifies as non-current — every exam carrying a
    Microsoft retirement date. Excluded from all advertised aggregates and shown
    under the retired groupings. Decided in the app repo, mirrored here."""
    return set(data.get("retired") or ())


# ── patching ──────────────────────────────────────────────────────────────

class Patcher:
    def __init__(self, check_only: bool):
        self.check_only = check_only
        self.changed_files = 0
        self.total_edits = 0
        self.problems = 0        # hand-fixes the script cannot make itself

    def apply(self, path: str, edits, transforms=()) -> None:
        """edits: list of (regex, replacement) applied in order.
        transforms: callables text -> (text, edits), for counts that have to be
        derived from the document itself rather than written as a fixed number."""
        if not os.path.exists(path):
            print(f"  skip (missing): {os.path.relpath(path, ROOT)}")
            return
        original = open(path).read()
        text = original
        n = 0
        for pattern, repl in edits:
            text, k = re.subn(pattern, repl, text)
            n += k
        for transform in transforms:
            text, k = transform(text)
            n += k
        rel = os.path.relpath(path, ROOT)
        if text != original:
            self.changed_files += 1
            self.total_edits += n
            if self.check_only:
                print(f"  DRIFT  {rel}: {n} replacement(s) would change content")
            else:
                with open(path, "w") as fh:
                    fh.write(text)
                print(f"  synced {rel}: {n} replacement(s)")


def exam_page_edits(code: str, count: int):
    """Anchored, value-agnostic edits for a single exam page."""
    c = str(count)
    return [
        # hero stat span
        (r'(am-cert-hero__stat-count">)\d+', r'\g<1>' + c),
        # "<n> AZ-900 practice questions" / "... cert-specific questions"
        (rf'\b\d+(\s+{re.escape(code)}\s+(?:practice|cert-specific)\s+questions)', c + r'\1'),
        # bare "<n> cert-specific questions" (own page only — related cards say "practice questions")
        (r'\b\d+(\s+cert-specific\s+questions)', c + r'\1'),
        # "with <n> AZ-900 practice" (meta/JSON-LD lead-ins without the word "questions" adjacent)
        (rf'\b\d+(\s+{re.escape(code)}\s+practice\b)', c + r'\1'),
        # "full <n>-question bank" in the exam simulator copy
        (r'(full\s+)\d+(-question\s+bank)', r'\g<1>' + c + r'\2'),
        # title/og:title/twitter:title pattern "AZ-700 Practice Questions — 396 Qs"
        (rf'({re.escape(code)} Practice Questions — )\d+( Qs)', r'\g<1>' + c + r'\2'),
        # app-FAQ JSON-LD/visible copy "full bank of <n> AZ-700 practice questions"
        (rf'(full bank of )\d+( {re.escape(code)} practice questions)', r'\g<1>' + c + r'\2'),
    ]


def patch_related_cards(text: str, counts: dict) -> tuple[str, int]:
    """In each <a class="related-card" href="/exams/<dir>/"> ... </a> block,
    rewrite the bare "<n> practice questions" hint to the linked exam's count."""
    edits = 0

    def repl(m):
        nonlocal edits
        block = m.group(0)
        href = re.search(r'href="/exams/([a-z]+-\d+)/"', block)
        if not href:
            return block
        code = href.group(1).upper()
        if code not in counts:
            return block
        new_block, k = re.subn(r'\b\d+(\s+practice\s+questions)',
                               str(counts[code]) + r'\1', block)
        edits += k
        return new_block

    text = re.sub(r'<a class="related-card"[^>]*>.*?</a>', repl, text, flags=re.S)
    return text, edits


def homepage_edits(total_label: str, metric_total: str, exam_count: int,
                   cert_paths: int, retired_count: int, catalogue_count: int):
    """Anchored aggregate edits for index.html. Each pattern is keyed off stable
    surrounding text so per-pillar roadmap counts ('5 exams') are never touched."""
    ec = str(exam_count)
    cp = str(cert_paths)
    return [
        # ── total questions (prose: "9,000 questions", "9,000 practice questions", "9,000 Questions") ──
        # Require a thousands-grouped number (>=1 comma-group) and a lookbehind so we never
        # start mid-number. This excludes exam codes ("AZ-204 practice questions") and bare
        # keyword commas ("exam prep, practice questions") — both must stay untouched.
        (r'(?<![\d,])\d{1,3}(?:,\d{3})+\+?(\s+(?:practice\s+)?[Qq]uestions)', total_label + r'\1'),
        # ── metric counters (anchored on the adjacent metric-label) ──
        (r'(class="metric-number[^"]*"[^>]*>)\d+\+?(</span>\s*<span class="metric-label">Questions)',
         r'\g<1>' + metric_total + r'\2'),
        (r'(class="metric-number[^"]*"[^>]*>)\d+(</span>\s*<span class="metric-label">Exams)',
         r'\g<1>' + ec + r'\2'),
        # ── exam count (each anchored to a stable phrase) ──
        (r'\|\s*\d+(\s+Exams</title>)', '| ' + ec + r'\1'),
        (r'\b\d+(\s+Microsoft\s+certification\s+exams)', ec + r'\1'),
        (r'across\s+\d+(\s+Microsoft\s+[Ee]xams)', 'across ' + ec + r'\1'),
        (r'across\s+\d+(\s+[Ee]xams)\b', 'across ' + ec + r'\1'),
        (r'\b\d+(\s+Microsoft\s+[Ee]xams)\b', ec + r'\1'),
        (r'Browse\s+the\s+\d+(\s+exams)', 'Browse the ' + ec + r'\1'),
        (r'\b\d+(\s+exams\s+spanning)', ec + r'\1'),
        # ── certification paths ──
        (r'\b\d+(\s+certification\s+paths)', cp + r'\1'),
        (r'\b\d+(\s+certification\s+routes)', cp + r'\1'),
        (r'\b\d+(\s+guided\s+certification\s+paths)', cp + r'\1'),
        # ── headline word-number "Twenty-six certifications." -> exam count word ──
        (r'(headline-accent">)[A-Za-z-]+(\s+certifications\.)',
         r'\g<1>' + number_word(exam_count) + r'\2'),
        # ── "Retired & retiring (N)" disclosure summaries (hero + footer) ──
        (r'(exam-retired-disclosure__summary">Retired &amp; retiring \()\d+(\))',
         r'\g<1>' + str(retired_count) + r'\2'),
        # ── JSON-LD ItemList entity count. This is deliberately NOT exam_count:
        # entity list = sit-able + retired reference pages, not the advertised
        # exam count — the ItemList enumerates every /exams/<code>/ page that
        # exists, current or retired, so search engines can still find retired
        # exam reference pages. ──
        (r'("numberOfItems":\s*)\d+', r'\g<1>' + str(catalogue_count)),
    ]


def patch_roadmap_category_counts(text: str, retired: set):
    """Rewrite each roadmap pillar's "<n> exams" chip to the number of sit-able
    exams pilled under it. Counted from the lifecycle set rather than from the
    exam-link--retired class, so stale markup cannot yield a stale count."""
    edits = 0
    seen = dict.fromkeys(
        re.findall(r'<div class="roadmap-category" data-category="([a-z-]+)"', text))
    for cat in seen:
        codes = []
        for cell in re.findall(rf'<div class="roadmap-cell" data-category="{cat}">(.*?)</div>',
                               text, flags=re.S):
            codes += re.findall(r'href="/exams/([a-z]+-\d+)/"', cell)
        n = sum(1 for c in codes if c.upper() not in retired)
        label = f"{n} exam" + ("s" if n != 1 else "")
        before = text
        text = re.sub(
            rf'(<div class="roadmap-category" data-category="{cat}">'
            rf'.*?roadmap-category__count">)[^<]*(</span>)',
            r'\g<1>' + label + r'\g<2>', text, count=1, flags=re.S)
        edits += text != before
    return text, edits


def patch_llms_section_counts(text: str, retired: set):
    """Rewrite each "### Group name (N)" heading in llms.txt to the number of
    sit-able exams bulleted under it. Retired exams keep their bullets — the
    heading counts what you can still book, the list stays a full reference."""
    edits = 0

    def repl(m):
        nonlocal edits
        title, shown, body = m.group(1), int(m.group(2)), m.group(3)
        codes = re.findall(r'^-\s+\[?([A-Z]{2}-\d{3})\b', body, flags=re.M)
        n = sum(1 for c in codes if c not in retired)
        if not codes or n == shown:
            return m.group(0)
        edits += 1
        return f"### {title} ({n})\n{body}"

    text = re.sub(r'^### (.+?) \((\d+)\)\n(.*?)(?=^#{2,3} |\Z)', repl, text,
                  flags=re.M | re.S)
    return text, edits


def patch_exam_code_lists(text: str, retired: set):
    """Drop retired codes from the homepage's spelled-out exam lists.

    The meta description, og:image:alt, JSON-LD keywords and the two "Azure Mastery
    covers N exams: ..." FAQ answers each enumerate every code. Leaving a retired
    code in a list introduced by a sit-able count reads as a miscount, so the list
    and the number have to move together. Rejoins in the list's own style — Oxford
    comma, bare "and", or neither."""
    def repl(m):
        run = m.group(0)
        codes = re.findall(r'[A-Z]{2}-\d{3}', run)
        kept = [c for c in codes if c not in retired]
        if len(kept) == len(codes) or len(kept) < 2:
            return run
        if re.search(r',\s+and\s+[A-Z]{2}-\d{3}$', run):
            return ", ".join(kept[:-1]) + ", and " + kept[-1]
        if re.search(r'\s+and\s+[A-Z]{2}-\d{3}$', run):
            return ", ".join(kept[:-1]) + " and " + kept[-1]
        return ", ".join(kept)

    # 3+ codes joined by ", " (optionally "and" before the last) — long enough to be
    # a catalogue enumeration, never a two-exam comparison in body copy.
    return re.subn(r'[A-Z]{2}-\d{3}(?:(?:,\s+|,?\s+and\s+)[A-Z]{2}-\d{3}){2,}', repl, text)


def patch_more_certifications(text: str, exam_count: int, retired: set):
    """The SEO h1 names a handful of exams then says "and <n> More Microsoft
    Certifications" — n has to be the sit-able total minus the ones already named."""
    def repl(m):
        named = {c for c in re.findall(r'[A-Z]{2}-\d{3}', m.group(1))} - retired
        return f"{m.group(1)}and {exam_count - len(named)} More"

    return re.subn(r'((?:[A-Z]{2}-\d{3},\s+)+)and \d+ More(?= Microsoft Certifications)',
                   repl, text)


def warn_retired_markup(p: "Patcher", retired: set, catalogue: set) -> None:
    """Report exam links whose retired treatment disagrees with the catalogue.

    The homepage marks retired exams with class="... exam-link--retired"; the
    /exams/ hub instead groups them under its #fam-retired section. Both are
    hand-maintained, so this is what catches an exam whose retirement date passed
    while nobody was looking. It only reports — the markup moves are a human's job
    (each link carries hand-written aria-label and grouping)."""
    print("retired markup:")
    problems = []

    if os.path.exists(INDEX_HTML):
        stale, premature = {}, {}
        for tag in re.findall(r'<a\b[^>]*>', open(INDEX_HTML).read()):
            href = re.search(r'href="/exams/([a-z]+-\d+)/"', tag)
            if not href:
                continue
            code = href.group(1).upper()
            marked = "exam-link--retired" in tag
            if code in retired and not marked:
                stale[code] = stale.get(code, 0) + 1
            elif code not in retired and marked:
                premature[code] = premature.get(code, 0) + 1
        for code, n in sorted(stale.items()):
            problems.append(f"index.html: {code} is non-current, but {n} link(s) still styled "
                            f"active — add exam-link--retired and move it into the disclosures")
        for code, n in sorted(premature.items()):
            problems.append(f"index.html: {code} is current, but {n} link(s) styled non-current")

    hub = os.path.join(EXAMS_DIR, "index.html")
    if os.path.exists(hub):
        text = open(hub).read()
        section = re.search(r'<section id="fam-retired".*?</section>', text, flags=re.S)
        grouped = {c.upper() for c in
                   re.findall(r'href="/exams/([a-z]+-\d+)/"', section.group(0))} if section else set()
        listed = {c.upper() for c in re.findall(r'href="/exams/([a-z]+-\d+)/"', text)}
        for code in sorted((retired & listed) - grouped):
            problems.append(f"exams/index.html: {code} is non-current but sits outside #fam-retired")
        for code in sorted(grouped - retired):
            problems.append(f"exams/index.html: {code} is current but sits under #fam-retired")
        for code in sorted(catalogue - retired - listed):
            problems.append(f"exams/index.html: {code} is current and has a page but no hub card")

    if not problems:
        print("  markup ok  retired treatment matches the catalogue")
        return
    for line in problems:
        print(f"  RETIRED   {line}")
    p.problems += len(problems)


def warn_itemlist_count(catalogue_count: int) -> None:
    """Report when the homepage JSON-LD ItemList's ListItem entries drift from
    catalogue_count. The ItemList deliberately enumerates every exam page that
    exists — entity list = sit-able + retired reference pages, not the
    advertised exam count — so this only warns; homepage_edits() is what keeps
    numberOfItems itself in sync."""
    if not os.path.exists(INDEX_HTML):
        return
    text = open(INDEX_HTML).read()
    m = re.search(r'"@type":\s*"ItemList".*?</script>', text, flags=re.S)
    if not m:
        print("  warning: homepage has no JSON-LD ItemList block to check.")
        return
    n = m.group(0).count('"@type": "ListItem"')
    if n != catalogue_count:
        print(f"  warning: homepage ItemList has {n} ListItem entries, but the "
              f"catalogue has {catalogue_count} exams — re-run with --refresh "
              f"or check index.html.")


def llms_edits(counts: dict, total_label: str, exam_count: int):
    """Counts in llms.txt: the header summary + the per-exam bullet list.
    Each bullet is '...(/exams/<dir>/): <n> in-app practice questions...'."""
    ec = str(exam_count)
    edits = [
        # header: "9,000+ practice questions cover 27 Microsoft certification exams"
        (r'\b[\d,]+\+?(\s+practice\s+questions\s+cover)', total_label + r'\1'),
        (r'cover\s+\d+(\s+Microsoft\s+certification\s+exams)', 'cover ' + ec + r'\1'),
        (r'## Exams covered \(\d+\)', f'## Exams covered ({ec})'),
    ]
    for code, n in counts.items():
        dir_ = code_to_dir(code)
        # Use \g<N> (not \1\2) — a bare \1 followed by digits, e.g. "\1" + "358",
        # would be misread by re as group reference \1358 / \13.
        edits.append(
            (rf'(/exams/{re.escape(dir_)}/\):\s*)\d+(\s+in-app\s+practice\s+questions)',
             r'\g<1>' + str(n) + r'\g<2>'))
    return edits


