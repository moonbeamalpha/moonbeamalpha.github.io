# Word forms for the homepage headline-accent ("Twenty-eight certifications.").
_ONES = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine"]
_TEENS = ["ten", "eleven", "twelve", "thirteen", "fourteen", "fifteen",
          "sixteen", "seventeen", "eighteen", "nineteen"]
_TENS = ["", "", "twenty", "thirty", "forty", "fifty", "sixty", "seventy", "eighty", "ninety"]


def number_word(n: int) -> str:
    """Capitalised English word for 0..99 (enough for exam counts)."""
    if n < 10:
        w = _ONES[n]
    elif n < 20:
        w = _TEENS[n - 10]
    elif n < 100:
        w = _TENS[n // 10] + ("-" + _ONES[n % 10] if n % 10 else "")
    else:
        return str(n)
    return w[0].upper() + w[1:]


# ── code helpers ──────────────────────────────────────────────────────────

def slug_to_code(slug: str) -> str:
    """az104 -> AZ-104 ; gh900 -> GH-900."""
    m = re.match(r"([a-z]+)(\d+)", slug)
    return f"{m.group(1).upper()}-{m.group(2)}"


def code_to_dir(code: str) -> str:
    """AZ-104 -> az-104 (the /exams/<dir>/ folder name)."""
    return code.lower()


def exam_accent(code: str) -> tuple[str, str]:
    """Read (--amh-accent, --amh-accent-2) from the exam's own page so its OG
    card matches the page's colour, falling back to the app's default cyan/blue
    when the page is missing or carries no accent (should not happen -- every
    shipped exams/<code>/index.html declares one)."""
    page = os.path.join(EXAMS_DIR, code_to_dir(code), "index.html")
    if os.path.exists(page):
        m = ACCENT_RE.search(open(page).read())
        if m:
            return m.group(1), m.group(2)
    return DEFAULT_ACCENT


